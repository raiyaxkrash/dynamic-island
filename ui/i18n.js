  function resolveLang(setting) {
    if (setting === 'ru' || setting === 'en') return setting;
    return (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
  }

  function t(lang, key, vars) {
    const dict = DICT[lang] || DICT.ru;
    let s = dict[key] ?? DICT.ru[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  }

  function plural(lang, n, key) {
    const forms = (DICT[lang] || DICT.ru)[key] || DICT.ru[key];
    if (lang !== 'ru') return n === 1 ? forms[0] : forms[1];
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
    return forms[2];
  }

  window.DI_I18N = { resolveLang, t, plural };
